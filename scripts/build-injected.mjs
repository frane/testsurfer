/**
 * Bundle the page-side engine (src/injected/*.ts) into one
 * self-contained function source, written to src/injected.gen.ts:
 *
 *     function installEngine(SER) {
 *       if (window.__tse) return window.__tse;
 *       <the modules, scope-hoisted into one IIFE>
 *       return __tseEngine.api;
 *     }
 *
 * `node scripts/build-injected.mjs --check` exits 1 when the committed
 * file is out of date instead of writing it.
 */

import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const out = `${root}src/injected.gen.ts`;

export async function engineSource() {
  const r = await build({
    entryPoints: [`${root}src/injected/index.ts`],
    bundle: true,
    write: false,
    format: 'iife',
    globalName: '__tseEngine',
    target: 'esnext',
    charset: 'utf8',
    legalComments: 'none',
    logLevel: 'silent',
  });
  // The engine runs as the page's own script did before the split: not in strict mode.
  const iife = r.outputFiles[0].text.trimEnd().replace(/^"use strict";\n/, '');
  return `function installEngine(SER) {\nif (window.__tse) return window.__tse;\n${iife}\nreturn __tseEngine.api;\n}`;
}

export async function generated() {
  return (
    '// Generated by scripts/build-injected.mjs from src/injected/*.ts. Do not edit.\n\n' +
    '/** Source of `installEngine(SER)`, the page-side locator engine (see src/injected/index.ts). */\n' +
    `export const ENGINE_SOURCE = ${JSON.stringify(await engineSource())};\n`
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = await generated();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(out, 'utf8');
    } catch {}
    // Windows checkouts may turn the committed file's newlines into CRLF.
    if (current.replace(/\r\n/g, '\n') !== text) {
      console.error('src/injected.gen.ts is out of date; run npm run build:injected');
      process.exit(1);
    }
  } else {
    writeFileSync(out, text);
  }
}
